package org.bg52.artifacts.listener;

import org.bg52.artifacts.Artifacts;
import org.bg52.artifacts.manager.MimicManager;
import org.bg52.artifacts.util.VersionUtil;
import org.bukkit.Material;
import org.bukkit.NamespacedKey;
import org.bukkit.entity.Entity;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;
import org.bukkit.event.entity.EntityDeathEvent;
import org.bukkit.event.entity.ItemSpawnEvent;
import org.bukkit.event.inventory.InventoryClickEvent;
import org.bukkit.event.inventory.InventoryOpenEvent;
import org.bukkit.event.inventory.PrepareItemCraftEvent;
import org.bukkit.event.world.LootGenerateEvent;
import org.bukkit.inventory.Inventory;
import org.bukkit.inventory.ItemStack;
import org.bukkit.inventory.meta.ItemMeta;
import org.bukkit.persistence.PersistentDataType;

/**
 * Tags naturally occurring slimeballs with CustomModelData and item model
 * so the resource pack displays the "real" vanilla slimeball texture while
 * untagged slimeballs use the transparent fake texture.
 *
 * Listens to:
 * - EntityDeathEvent (non-mimic entities dropping slimeballs)
 * - PrepareItemCraftEvent (crafted slimeballs in the result slot)
 * - InventoryOpenEvent (loot table / chest containers)
 * - LootGenerateEvent (world loot generation)
 * - ItemSpawnEvent (any slimeball entity spawning in the world)
 * - InventoryClickEvent (catch-all for player item interactions/trades)
 */
public class SlimeballListener implements Listener {

    public static final int REAL_SLIMEBALL_CMD = 1;
    public static final String REAL_SLIMEBALL_MODEL_KEY = "real_slime_ball";
    private static final NamespacedKey REAL_SLIMEBALL_KEY = new NamespacedKey("artifacts", REAL_SLIMEBALL_MODEL_KEY);
    private static final NamespacedKey MIMIC_KEY = new NamespacedKey("artifacts", "mimic");
    private static final NamespacedKey SYNTHETIX_ENTITY_KEY = new NamespacedKey("synthetix", "entity_id");

    private final Artifacts plugin;
    private final MimicManager mimicManager;

    public SlimeballListener(Artifacts plugin, MimicManager mimicManager) {
        this.plugin = plugin;
        this.mimicManager = mimicManager;
    }

    public SlimeballListener() {
        this(null, null);
    }

    /**
     * Tag slimeballs dropped by non-mimic entity deaths.
     */
    @EventHandler(priority = EventPriority.NORMAL)
    public void onEntityDeath(EntityDeathEvent event) {
        Entity entity = event.getEntity();

        // Skip mimic entities — they have their own drop logic
        if (isMimic(entity)) {
            return;
        }

        for (ItemStack drop : event.getDrops()) {
            tagIfSlimeball(drop);
        }
    }

    /**
     * Tag slimeballs in crafting result slots.
     */
    @EventHandler(priority = EventPriority.NORMAL)
    public void onPrepareCraft(PrepareItemCraftEvent event) {
        if (event.getInventory() == null) {
            return;
        }
        ItemStack result = event.getInventory().getResult();
        if (result != null && result.getType() == Material.SLIME_BALL && shouldTag(result)) {
            ItemStack tagged = tagSlimeball(result.clone());
            event.getInventory().setResult(tagged);
        }
    }

    /**
     * Tag slimeballs generated in chests/containers when opened.
     */
    @EventHandler(priority = EventPriority.NORMAL)
    public void onInventoryOpen(InventoryOpenEvent event) {
        Inventory inventory = event.getInventory();
        ItemStack[] contents = inventory.getContents();
        boolean changed = false;

        for (int i = 0; i < contents.length; i++) {
            ItemStack item = contents[i];
            if (item != null && item.getType() == Material.SLIME_BALL && shouldTag(item)) {
                contents[i] = tagSlimeball(item);
                changed = true;
            }
        }

        if (changed) {
            inventory.setContents(contents);
        }
    }

    /**
     * Tag slimeballs generated by world loot tables.
     */
    @EventHandler(priority = EventPriority.NORMAL)
    public void onLootGenerate(LootGenerateEvent event) {
        if (event.getLoot() == null) {
            return;
        }
        for (ItemStack item : event.getLoot()) {
            tagIfSlimeball(item);
        }
    }

    /**
     * Tag any slimeball item entity that spawns in the world (drops, dispensers, broken containers, pandas, etc.).
     */
    @EventHandler(priority = EventPriority.NORMAL)
    public void onItemSpawn(ItemSpawnEvent event) {
        ItemStack item = event.getEntity().getItemStack();
        if (item.getType() == Material.SLIME_BALL && shouldTag(item)) {
            ItemStack tagged = tagSlimeball(item);
            event.getEntity().setItemStack(tagged);
        }
    }

    /**
     * Intercept clicks on untagged slimeballs in inventories (e.g. merchant trades, shift clicks).
     */
    @EventHandler(priority = EventPriority.NORMAL, ignoreCancelled = true)
    public void onInventoryClick(InventoryClickEvent event) {
        ItemStack current = event.getCurrentItem();
        if (current != null && current.getType() == Material.SLIME_BALL && shouldTag(current)) {
            tagSlimeball(current);
        }
        ItemStack cursor = event.getCursor();
        if (cursor != null && cursor.getType() == Material.SLIME_BALL && shouldTag(cursor)) {
            tagSlimeball(cursor);
        }
    }

    /**
     * Check if an entity is a Mimic.
     */
    private boolean isMimic(Entity entity) {
        if (entity == null) {
            return false;
        }
        if (mimicManager != null && mimicManager.isMimicEntity(entity)) {
            return true;
        }
        if (entity.getPersistentDataContainer().has(MIMIC_KEY, PersistentDataType.BYTE)) {
            return true;
        }
        if (entity.getPersistentDataContainer().has(SYNTHETIX_ENTITY_KEY, PersistentDataType.STRING)) {
            String entityId = entity.getPersistentDataContainer().get(SYNTHETIX_ENTITY_KEY, PersistentDataType.STRING);
            if ("mimic".equalsIgnoreCase(entityId)) {
                return true;
            }
        }
        return false;
    }

    /**
     * Tag an ItemStack in-place if it is an untagged slimeball.
     */
    public static void tagIfSlimeball(ItemStack item) {
        if (item != null && item.getType() == Material.SLIME_BALL && shouldTag(item)) {
            tagSlimeball(item);
        }
    }

    /**
     * Determine whether a slimeball should be tagged.
     * Keeps logic generalized while protecting custom items that already have specific models.
     */
    public static boolean shouldTag(ItemStack item) {
        if (item == null || item.getType() != Material.SLIME_BALL) {
            return false;
        }

        ItemMeta meta = item.getItemMeta();
        if (meta == null) {
            return true;
        }

        // Already tagged as real slimeball
        if (meta.hasCustomModelData() && meta.getCustomModelData() == REAL_SLIMEBALL_CMD) {
            return false;
        }

        // Special case: Preserve custom items with other CustomModelData values (from other plugins/systems)
        if (meta.hasCustomModelData() && meta.getCustomModelData() != 0) {
            return false;
        }

        // Special case: Preserve 1.21.3+ custom item models from other plugins
        if (VersionUtil.supportsItemModel()) {
            try {
                java.lang.reflect.Method hasItemModelMethod = meta.getClass().getMethod("hasItemModel");
                if ((boolean) hasItemModelMethod.invoke(meta)) {
                    java.lang.reflect.Method getItemModelMethod = meta.getClass().getMethod("getItemModel");
                    NamespacedKey currentModel = (NamespacedKey) getItemModelMethod.invoke(meta);
                    if (currentModel != null && !currentModel.equals(REAL_SLIMEBALL_KEY)) {
                        return false;
                    }
                }
            } catch (Exception ignored) {
            }
        }

        return true;
    }

    /**
     * Apply the real slimeball custom model data and item model to an ItemStack.
     * Sets CustomModelData (1) and ItemModel (artifacts:real_slime_ball on 1.21.3+).
     *
     * @return the modified ItemStack
     */
    @SuppressWarnings("deprecation")
    public static ItemStack tagSlimeball(ItemStack item) {
        if (!shouldTag(item)) {
            return item;
        }

        ItemMeta meta = item.getItemMeta();
        if (meta == null) {
            meta = org.bukkit.Bukkit.getItemFactory().getItemMeta(Material.SLIME_BALL);
            if (meta == null) {
                return item;
            }
        }

        meta.setCustomModelData(REAL_SLIMEBALL_CMD);

        if (VersionUtil.supportsItemModel()) {
            VersionUtil.setItemModel(meta, REAL_SLIMEBALL_KEY);
        }

        item.setItemMeta(meta);
        return item;
    }

    /**
     * Check if an ItemStack is already tagged as a real slimeball.
     */
    public static boolean isRealSlimeball(ItemStack item) {
        if (item == null || item.getType() != Material.SLIME_BALL) {
            return false;
        }
        ItemMeta meta = item.getItemMeta();
        if (meta == null) {
            return false;
        }
        return meta.hasCustomModelData() && meta.getCustomModelData() == REAL_SLIMEBALL_CMD;
    }
}

